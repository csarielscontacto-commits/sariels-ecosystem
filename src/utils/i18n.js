// ================================================================
// 🌐 CLASE PRINCIPAL DE IDIOMAS
// ================================================================

class CsarielsI18n {
    constructor() {
        this.actual = 'es';
        this.traducciones = TRADUCCIONES;
        this._listeners = [];
        this._cargarIdiomaGuardado();
    }

    // ================================================================
    // 🔄 CARGAR IDIOMA GUARDADO
    // ================================================================
    
    _cargarIdiomaGuardado() {
        try {
            const saved = localStorage.getItem('csariels_idioma');
            if (saved && this.traducciones[saved]) {
                this.actual = saved;
            }
        } catch (e) {
            console.warn('⚠️ Error cargando idioma guardado:', e);
        }
        return this.actual;
    }

    // ================================================================
    // 📋 OBTENER TRADUCCIÓN
    // ================================================================
    
    t(key, idioma = null) {
        const lang = idioma || this.actual;
        const traducciones = this.traducciones[lang];
        if (!traducciones) {
            console.warn(`⚠️ Idioma "${lang}" no encontrado, usando español`);
            return this.traducciones.es?.[key] || key;
        }
        return traducciones[key] || key;
    }

    // ================================================================
    // 🔄 CAMBIAR IDIOMA
    // ================================================================
    
    cambiar(idioma) {
        if (!idioma || idioma === this.actual) return;
        if (!this.traducciones[idioma]) {
            console.warn(`⚠️ Idioma "${idioma}" no disponible`);
            return;
        }
        
        this.actual = idioma;
        try {
            localStorage.setItem('csariels_idioma', idioma);
        } catch (e) {}
        
        this._notificarCambio(idioma);
        console.log(`🌐 Idioma cambiado a: ${idioma}`);
        return this.actual;
    }

    // ================================================================
    // 📢 NOTIFICAR CAMBIO
    // ================================================================
    
    _notificarCambio(idioma) {
        const event = new CustomEvent('idioma-cambiado', {
            detail: { idioma }
        });
        document.dispatchEvent(event);
        
        // Notificar a listeners
        this._listeners.forEach(callback => {
            try {
                callback(idioma);
            } catch (e) {
                console.warn('Error en listener de idioma:', e);
            }
        });
    }

    // ================================================================
    // 👂 ESCUCHAR CAMBIOS
    // ================================================================
    
    onCambio(callback) {
        if (typeof callback === 'function') {
            this._listeners.push(callback);
        }
        return this;
    }

    // ================================================================
    // 🖥️ APLICAR TRADUCCIONES AL DOM
    // ================================================================
    
    aplicarAlDOM() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const texto = this.t(key);
            if (texto && texto !== key) {
                el.textContent = texto;
            }
        });
        
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const texto = this.t(key);
            if (texto && texto !== key) {
                el.placeholder = texto;
            }
        });
        
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const texto = this.t(key);
            if (texto && texto !== key) {
                el.title = texto;
            }
        });
    }

    // ================================================================
    // 📋 OBTENER IDIOMA ACTUAL
    // ================================================================
    
    getIdioma() {
        return this.actual;
    }

    // ================================================================
    // 📋 OBTENER TODOS LOS IDIOMAS DISPONIBLES
    // ================================================================
    
    getIdiomasDisponibles() {
        return Object.keys(this.traducciones);
    }

    // ================================================================
    // 📋 OBTENER NOMBRE DEL IDIOMA
    // ================================================================
    
    getNombreIdioma(idioma = null) {
        const lang = idioma || this.actual;
        const nombres = {
            es: '🇪🇸 Español',
            en: '🇬🇧 English',
            fr: '🇫🇷 Français'
        };
        return nombres[lang] || lang;
    }
}

